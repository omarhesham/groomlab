"""Writes the C API's function reference into the docs from the header's own comments.

    python tools/dev/capi_reference.py          # rewrite the reference in web/content/docs/c-api.mdx
    python tools/dev/capi_reference.py --check  # exit 1 when the page is out of date (ctest capi.reference_docs)

engine/capi/include/groomlab/groomlab_c.h is the source of truth: each "/* ---- Section ---- */"
becomes a heading, each comment its declarations' description (declarations without a comment of
their own join the one before), and a comment followed by a blank line the section's intro. The
page keeps everything outside the markers below as written.
"""
import argparse
import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, "engine", "capi", "include", "groomlab", "groomlab_c.h")
PAGE = os.path.join(ROOT, "web", "content", "docs", "c-api.mdx")
BEGIN = "{/* BEGIN reference: generated by tools/dev/capi_reference.py from groomlab_c.h; do not edit */}"
END = "{/* END reference */}"

SECTION = re.compile(r"^/\* -+ (.+?) -+ \*/$")
IDENT = re.compile(r"\b((?:gl|GL|GROOMLAB)_[A-Za-z0-9_]+\b(?:\(\))?)")


def prose(lines):
    """Comment lines (comment_text) as MDX: identifiers in code spans, the rest escaped for MDX."""
    out = []
    for i, line in enumerate(lines):
        if i and line.startswith("- ") != lines[i - 1].startswith("- "):
            out.append("")  # a blank line between a list and the text around it
        out.append(prose_line(line))
    return "\n".join(out)


def prose_line(text):
    out = []
    for i, part in enumerate(text.split("`")):
        if i % 2:
            out.append("`" + part + "`")
            continue
        part = part.replace("\\", "\\\\").replace("*", "\\*")
        part = part.replace("<", "&lt;").replace(">", "&gt;").replace("{", "&#123;").replace("}", "&#125;")
        out.append(IDENT.sub(r"`\1`", part))
    return "".join(out)


def comment_text(lines):
    """A comment as Markdown lines: running text joined into paragraphs, lines indented further
    than the text (" *   "width"  per point...") as list items of their own."""
    out = []
    for line in lines:
        line = line.strip()
        line = re.sub(r"^/\*+", "", line)
        line = re.sub(r"\*+/$", "", line)
        line = re.sub(r"^\*(?!/)", "", line)
        text = line.strip()
        if not text:
            continue
        if line.startswith("   "):  # indented past the comment's own "* " margin: a list item
            out.append("- " + re.sub(r"\s{2,}", " ", text))
        elif out and not out[-1].startswith("- "):
            out[-1] += " " + text
        else:
            out.append(text)
    return out


def parse(header_text):
    """[(section, [("intro", text) | ("item", comment, [declaration, ...])])]"""
    lines = header_text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith('extern "C"')) + 1
    end = max(i for i, l in enumerate(lines) if l.startswith("#ifdef __cplusplus"))
    sections = []
    entries = None
    pending = None  # a comment not yet given to a declaration
    i = start
    while i < end:
        line = lines[i]
        stripped = line.strip()
        m = SECTION.match(stripped)
        if m:
            entries = []
            sections.append((m.group(1), entries))
            pending = None
            i += 1
            continue
        if stripped.startswith("#"):  # the extern "C" guard's #endif
            i += 1
            continue
        if not stripped:
            if pending and entries is not None:
                entries.append(("intro", pending))
            pending = None
            i += 1
            continue
        if stripped.startswith("/*"):
            block = [line]
            while "*/" not in lines[i]:
                i += 1
                block.append(lines[i])
            pending = comment_text(block)
            i += 1
            continue
        # A declaration: to its ";" (a struct or enum body to its closing "};" or "} name;").
        block = [line.rstrip()]
        opens = line.count("{") - line.count("}")
        while not (opens <= 0 and block[-1].rstrip().endswith(";")):
            i += 1
            block.append(lines[i].rstrip())
            opens += lines[i].count("{") - lines[i].count("}")
        i += 1
        if "{" in block[0]:
            decl = "\n".join(block)
        else:
            decl = re.sub(r"\s+", " ", " ".join(b.strip() for b in block)).replace("( ", "(")
        decl = re.sub(r"^GL_API ", "", decl)
        if pending is not None or not entries or entries[-1][0] != "item":
            entries.append(("item", pending or [], [decl]))
        else:
            entries[-1][2].append(decl)
        pending = None
    return sections


def render(sections):
    out = [BEGIN, ""]
    for title, entries in sections:
        out += ["### " + title, ""]
        for entry in entries:
            if entry[0] == "intro":
                out += [prose(entry[1]), ""]
                continue
            _, comment, decls = entry
            out += ["```c"] + decls + ["```", ""]
            if comment:
                out += [prose(comment), ""]
    out.append(END)
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the page is out of date")
    args = parser.parse_args()
    with io.open(HEADER, encoding="utf-8") as f:
        reference = render(parse(f.read()))
    with io.open(PAGE, encoding="utf-8") as f:
        page = f.read()
    if BEGIN not in page or END not in page:
        sys.exit("%s has no reference markers" % PAGE)
    head, rest = page.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    updated = head + reference + tail
    if args.check:
        if updated != page:
            sys.exit("web/content/docs/c-api.mdx is out of date with groomlab_c.h: run python tools/dev/capi_reference.py")
        print("c-api.mdx reference is up to date")
        return
    if updated != page:
        with io.open(PAGE, "w", encoding="utf-8", newline="\n") as f:
            f.write(updated)
        print("updated " + os.path.relpath(PAGE, ROOT))
    else:
        print("up to date")


if __name__ == "__main__":
    main()
